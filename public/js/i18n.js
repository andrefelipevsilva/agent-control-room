export const lang = (navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en'
export const locale = lang === 'pt' ? 'pt-BR' : 'en-US'

/** Text for a key; {0}, {1}... (or {name}) are replaced by the arguments. */
export function t(key, ...args) {
  let s = TEXT[lang][key] ?? TEXT.en[key] ?? key
  if (args.length === 1 && args[0] && typeof args[0] === 'object') {
    for (const [k, v] of Object.entries(args[0])) s = s.replaceAll(`{${k}}`, v)
  } else {
    args.forEach((v, i) => (s = s.replaceAll(`{${i}}`, v)))
  }
  return s
}

/** Singular or plural key: plural('agents', 3) → "3 agents". */
export const plural = (base, n) => (n === 1 ? t(`${base}1`) : t(`${base}N`, n))

export function applyStaticText(root = document) {
  document.documentElement.lang = locale
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n)
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle)
  for (const el of root.querySelectorAll('[data-i18n-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel))
    if (!el.title) el.title = t(el.dataset.i18nLabel)
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder)
}
